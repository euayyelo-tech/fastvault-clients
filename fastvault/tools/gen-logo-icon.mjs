// Rebuilds fastvault/branding/logo.icon.ts from branding/src/lockup-flat.svg.
// Run: cd fastvault/tools && node gen-logo-icon.mjs
// The wordmark is Bricolage Grotesque ExtraBold outlined to paths (no font
// ships); the flat lockup carries two paths — the ink letters and the mint V.
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const B = new URL("../branding/", import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1");
const flat = readFileSync(join(B, "src/lockup-flat.svg"), "utf8");
const paths = [...flat.matchAll(/<path d="([^"]+)" fill="(#[0-9A-F]{6})"\/>/g)].map((m) => ({
  d: m[1],
  fill: m[2],
}));
if (paths.length !== 2)
  throw new Error(`expected 2 wordmark paths in lockup-flat.svg, got ${paths.length}`);
const ink = paths.find((p) => p.fill === "#08201C").d;
const mint = paths.find((p) => p.fill === "#2BBE8B").d;

const ARCS = [
  [10, "63.74 51.81", "63.74 68.19"],
  [18, "68.33 45.26", "68.33 74.74"],
  [26, "72.92 38.71", "72.92 81.29"],
  [34, "77.52 32.15", "77.52 87.85"],
  [42, "82.11 25.6", "82.11 94.4"],
];
const arcLines = ARCS.map(
  ([r, a, b]) =>
    `      <path d="M${a} A${r} ${r} 0 1 0 ${b}" fill="none" class="tw-stroke-marketing-logo" stroke-width="7" stroke-linecap="round"></path>`,
).join("\n");

const out = `import { svg } from "../svg";

// FastVault lockup: the mark (arcs are strokes, so they take tw-stroke-*; the dot and bar are
// fills) and the wordmark, Bricolage Grotesque ExtraBold outlined to paths — no font ships. The
// whole thing follows the theme through tw-*-marketing-logo except the V of "Vault", which is
// mint on every ground: it sits where the mark opens, and that is the brand's one signature.
// Generated by fastvault/tools/gen-logo-icon.mjs from branding/src/lockup-flat.svg.
export const BitwardenLogo = svg\`
  <svg viewBox="0 0 238 72" xmlns="http://www.w3.org/2000/svg">
    <title>FastVault</title>
    <g transform="translate(-6.667 -4) scale(0.6667)">
      <circle cx="58" cy="60" r="4.2" class="tw-fill-marketing-logo"></circle>
${arcLines}
      <rect x="88" y="14" width="6" height="92" rx="3" class="tw-fill-marketing-logo"></rect>
    </g>
    <path d="${ink}" class="tw-fill-marketing-logo"></path>
    <path d="${mint}" fill="#2BBE8B"></path>
  </svg>
\`;
`;
writeFileSync(join(B, "logo.icon.ts"), out);
console.log("wrote branding/logo.icon.ts", out.length, "bytes");
